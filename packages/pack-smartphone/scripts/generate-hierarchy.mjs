/**
 * Read smartphone-hierarchy.md and write src/hierarchy.generated.ts.
 * Run from the repo root: `npm run generate`.
 */
/* global console */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = join(root, 'smartphone-hierarchy.md');
const outPath = join(root, 'src/hierarchy.generated.ts');

const UNIT_IN_MM = {
  mm: 1,
  µm: 1e-3,
  um: 1e-3,
  nm: 1e-6,
  pm: 1e-9,
};

const markdown = readFileSync(sourcePath, 'utf8');
const nodes = parseHierarchy(markdown);
if (nodes.length !== 188) {
  throw new Error(`expected 188 nodes, parsed ${nodes.length}`);
}
const ids = new Set();
for (const node of nodes) {
  if (ids.has(node.id)) throw new Error(`duplicate id ${node.id}`);
  ids.add(node.id);
  if (node.parentId !== null && !ids.has(node.parentId)) {
    throw new Error(`${node.id} is listed before its parent ${node.parentId}`);
  }
  if (!(node.sizeMm > 0)) throw new Error(`${node.id} has no characteristic size`);
}

writeFileSync(outPath, render(nodes));
console.log(`wrote ${nodes.length} nodes to ${outPath}`);

/**
 * @param {string} markdown
 * @returns {Array<{id:string,name:string,parentId:string|null,kind:string,status:string,sizeMm:number,countMark:string|null}>}
 */
export function parseHierarchy(markdown) {
  const chunks = markdown.split(/^### /m).slice(1);
  return chunks.map((chunk) => {
    const header = chunk.split('\n', 1)[0] ?? '';
    const headerMatch = /^(?<name>.+) \(`(?<id>[^`]+)`\)\s*$/.exec(header);
    if (!headerMatch?.groups) throw new Error(`bad heading: ${header}`);
    const id = headerMatch.groups.id;
    const name = headerMatch.groups.name.replace(/ \((view|process)\)$/, '');
    const field = (label) => {
      const match = new RegExp(`^- ${label}:\\s*(.+)$`, 'm').exec(chunk);
      if (!match) throw new Error(`${id} is missing ${label}`);
      return match[1].trim();
    };
    const parentRaw = field('Parent');
    const parentMatch = /`([^`]+)`/.exec(parentRaw);
    const parentId = parentMatch ? parentMatch[1] : null;
    const status = field('Status');
    if (status !== 'built' && status !== 'planned') throw new Error(`${id} status ${status}`);
    const kindRaw = field('Kind');
    const kind = kindRaw.split(/\s/)[0];
    if (kind !== 'part' && kind !== 'view' && kind !== 'process') throw new Error(`${id} kind ${kindRaw}`);
    const size = field('Characteristic size');
    const sizeMatch = /^([0-9]+(?:\.[0-9]+)?)\s+(mm|µm|um|nm|pm)\b/.exec(size);
    if (!sizeMatch) throw new Error(`${id} size ${size}`);
    const sizeMm = Number(sizeMatch[1]) * UNIT_IN_MM[sizeMatch[2]];
    return {
      id,
      name,
      parentId,
      kind,
      status,
      sizeMm,
      countMark: countMark(field('Count')),
    };
  });
}

/** @param {string} count */
function countMark(count) {
  if (/^(1\b|Not applicable|One representative|Typically one)/i.test(count)) return null;
  const leading = /^(~?[0-9]+(?:\.[0-9]+)?)\s+(billion|million|thousand)\b/i.exec(count);
  if (leading) return `×${leading[1]} ${leading[2].toLowerCase()}`;
  return null;
}

/** @param {ReturnType<typeof parseHierarchy>} nodes */
function render(nodes) {
  const body = nodes
    .map((node) => {
      const parent = node.parentId === null ? 'null' : `'${node.parentId}'`;
      const mark = node.countMark === null ? 'null' : `'${node.countMark}'`;
      return `  { id: '${node.id}', name: '${escapeText(node.name)}', parentId: ${parent}, kind: '${node.kind}', status: '${node.status}', sizeMm: ${formatNumber(node.sizeMm)}, countMark: ${mark} },`;
    })
    .join('\n');
  return `// Generated by scripts/generate-hierarchy.mjs from smartphone-hierarchy.md.
// Do not edit by hand. Re-run the script after the hierarchy changes.

export type HierarchyKind = 'part' | 'view' | 'process';

export type HierarchyStatus = 'built' | 'planned';

export type HierarchyNode = {
  id: string;
  /** Heading name, without a trailing "(view)" or "(process)". */
  name: string;
  parentId: string | null;
  kind: HierarchyKind;
  status: HierarchyStatus;
  /** Characteristic size in millimetres. */
  sizeMm: number;
  /**
   * Set when the node's count is a magnitude above one.
   * Already includes the times sign, e.g. \`×~15 billion\`.
   */
  countMark: string | null;
};

export const hierarchyNodes: readonly HierarchyNode[] = [
${body}
];
`;
}

/** @param {string} text */
function escapeText(text) {
  return text.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

/** @param {number} value */
function formatNumber(value) {
  if (Number.isInteger(value)) return String(value);
  return String(Number(value.toPrecision(12)));
}
